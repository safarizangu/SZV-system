-- Create custom_requests table if missing
CREATE TABLE IF NOT EXISTS `custom_requests` (
  `id`                int NOT NULL AUTO_INCREMENT,
  `full_name`         varchar(150) NOT NULL,
  `email`             varchar(200) NOT NULL,
  `phone`             varchar(50)  DEFAULT NULL,
  `country`           varchar(100) DEFAULT NULL,
  `adults`            int          DEFAULT 2,
  `children`          int          DEFAULT 0,
  `duration_days`     int          DEFAULT NULL,
  `start_date`        date         DEFAULT NULL,
  `flexibility`       varchar(50)  DEFAULT NULL,
  `total_budget`      varchar(100) DEFAULT NULL,
  `accommodation_pref`varchar(100) DEFAULT NULL,
  `destinations`      text         DEFAULT NULL,
  `activities`        text         DEFAULT NULL,
  `dietary`           varchar(200) DEFAULT NULL,
  `special_requests`  text         DEFAULT NULL,
  `message`           text         DEFAULT NULL,
  `source`            varchar(50)  DEFAULT 'website',
  `status`            enum('new','reviewed','quoted','converted','closed') DEFAULT 'new',
  `assigned_to`       int          DEFAULT NULL,
  `admin_notes`       text         DEFAULT NULL,
  `created_at`        timestamp    DEFAULT CURRENT_TIMESTAMP,
  `updated_at`        timestamp    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_status` (`status`),
  KEY `idx_created` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
